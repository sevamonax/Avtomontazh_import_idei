# -*- coding: utf-8 -*-
"""Где на самом деле звучит речь. Перенесено из конвейера длинного (`build_edl.py`)
без изменений по существу — это место дважды стоило сборки, переписывать его
заново значит наступить на те же грабли.

Два правила, добытых кровью 30.07 (`ЭКРАН.md` §8):
  · границы кусков берутся из огибающей звука, а не из таймкодов слов —
    whisper растягивает последнее слово фразы на следующую тишину;
  · порог, которым ищут речь, срезает тихие приступы и хвосты слов, поэтому
    граница дотягивается по низкому порогу с перешагиванием провалов до 0,22 с
    («катастрофа» теряла своё «-фа»: перед взрывным согласным смычка даёт
    настоящую тишину и читается как конец слова).
"""
import subprocess
import wave

import numpy as np

FRAME = 0.02          # шаг огибающей, с
SR = 16000

_ENV = {}


def izvlech_wav(src, dst):
    """16 кГц моно из видео — вход всех замеров звука."""
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src,
                    "-vn", "-ac", "1", "-ar", str(SR), "-acodec", "pcm_s16le", dst],
                   check=True)
    return dst


def read_wav(path):
    w = wave.open(path)
    return np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16)


def envelope(wav_path):
    """Уровень сигнала по кадрам, дБ. Кэшируется — считается по разу на дубль."""
    if wav_path in _ENV:
        return _ENV[wav_path]
    w = wave.open(wav_path)
    sr, n = w.getframerate(), w.getnframes()
    a = np.frombuffer(w.readframes(n), dtype=np.int16).astype(np.float32) / 32768.0
    step = int(sr * FRAME)
    m = len(a) // step
    rms = np.sqrt((a[:m * step].reshape(m, step) ** 2).mean(axis=1) + 1e-12)
    db = 20 * np.log10(rms)
    _ENV[wav_path] = db
    return db


def expand(t, db, forward, limit=0.35, bridge=0.22):
    """Дотягивает границу до настоящего края слова.

    🔑 ПОРОГ СЧИТАЕТСЯ ОТ ШУМА ЭТОЙ ЗАПИСИ, А НЕ ОТ ПИКА. В конвейере длинного
    он был «на 34 дБ ниже речи», и это работало, потому что камера писала в
    паузах цифровую тишину (−120 дБ). На сырье «ПРИМЕР» комнатный тон
    держится на −40 дБ, порог получался −55 — то есть НИКОГДА не срабатывал, и
    граница каждый раз уходила на весь лимит 0,35 с. Замер: 0,465 с добавлено
    перед каждым куском и 0,455 после — ровно максимум, все 23 раза. В ролике
    это дало паузу 0,84 с на склейке вместо задуманных 0,25.

    Теперь порог стоит на 5 дБ выше шумовой полки записи: тихий хвост слова
    («катастрофа» теряла своё «-фа») по-прежнему дотягивается, а комнатный тон
    честно читается как конец слова.
    """
    quiet = max(np.percentile(db, 10) + 5.0, np.percentile(db, 95) - 34.0, -62.0)
    n = len(db)
    step = 1 if forward else -1
    i = int(round(t / FRAME))
    best = i
    j, gap = i, 0
    for _ in range(int(limit / FRAME)):
        j += step
        if j < 0 or j >= n:
            break
        if db[j] < quiet:
            gap += 1
            if gap * FRAME > bridge:      # провал затянулся — слово правда кончилось
                break
        else:
            gap = 0
            best = j                      # звук вернулся, значит слово ещё идёт
    return best * FRAME


def tihiy_porog(db):
    """Полка тишины этой записи — тот же порог, которым `expand` ищет край слова."""
    return max(np.percentile(db, 10) + 5.0, np.percentile(db, 95) - 34.0, -62.0)


def dolya_zvuka(wav_path, t0, t1):
    """Есть ли в промежутке звук — то есть слово, которое не увидел `speech_runs`.

    🔑 ЗАЧЕМ. Всплески ищутся порогом «на 22 дБ ниже речи» — он намеренно груб,
    иначе комнатный тон читается как речь. Цена грубости: тихое слово между
    двумя всплесками не попадает ни в один из них, а рез пауз ужимает эту
    «паузу» до 0,25 с — и слово исчезает из ролика. На сборке 12.09.2026 так
    пропали «39» в «ухудшение качества аж в 39 процентов» (ролик), «почему это» в
    «назови мне 10 причин, почему это произошло» (ролик), «длинной» в «задача
    кажется слишком длинной» (ролик) и пол-фразы «те предположения, которые
    сделали сами» (ролик). Все четыре — несущие слова, и ни одна проверка их не
    искала: в плане они не значились, значит и пропасть не могли.

    Порог здесь чувствительнее (тот же, что у `expand`), потому что вопрос
    другой: не «где речь», а «точно ли тут пусто».

    Возвращается ДОЛЯ звучащего, а не «да/нет»: вдох и шорох стула дают короткий
    всплеск в любой паузе, а слово заполняет её. По доле эти случаи различаются,
    по факту наличия звука — нет. Первая версия отвечала «да/нет» и требовала
    паузу короче 1,6 с; на сборке 12.09 два места с потерянными словами —
    «те предположения, которые сделали сами» (1,73 с) и «пойти не так» (1,72 с) —
    в этот предел не влезли на сотые доли секунды. Предел, который отсекает
    нужное на сотых, выбран неправильно.
    """
    db = envelope(wav_path)
    quiet = tihiy_porog(db)
    i0, i1 = int(round(t0 / FRAME)), int(round(t1 / FRAME))
    i0, i1 = max(0, i0), min(len(db), i1)
    if i1 <= i0:
        return 0.0
    zvuchit = sum(1 for j in range(i0, i1) if db[j] > quiet)
    return float(zvuchit) / (i1 - i0)


def speech_runs(wav_path):
    """Всплески речи: [начало, конец] в секундах сырья."""
    db = envelope(wav_path)
    m = len(db)
    # в паузах камера пишет цифровую тишину (−120 дБ), речь около −20,
    # поэтому порог отсчитываем от уровня речи, а не от медианы дорожки
    thr = max(np.percentile(db, 95) - 22.0, -55.0)
    voiced = db > thr
    runs, i = [], 0
    while i < m:
        if voiced[i]:
            j = i
            while j < m and voiced[j]:
                j += 1
            runs.append([i * FRAME, j * FRAME])
            i = j
        else:
            i += 1
    # заклеиваем дырки короче 0.10 с — это смычки внутри слова, а не паузы
    glued = []
    for r in runs:
        if glued and r[0] - glued[-1][1] < 0.10:
            glued[-1][1] = r[1]
        else:
            glued.append(list(r))
    # ⚠️ Края всплесков здесь НЕ растягиваются. `expand` дотягивает границу РЕЗА
    # до края слова (`ЭКРАН.md` §8), но применённый к самим всплескам он раздувает каждый
    # на 0,35 с в обе стороны — соседи начинают делить один и тот же звук, и
    # детектор брошенных заходов выдумывает повторы. Ровно этим 30.07 чуть не
    # была разрезана чистая фраза. Проверка: сумма всплесков не может превышать
    # длину дорожки; на первой версии этого файла вышло 110 %.
    return [r for r in glued if r[1] - r[0] >= 0.06]


def gromkost(wav_path, a=None, b=None):
    """Средний уровень речи в дБ на отрезке — для замеров звука (шаг 4 плана)."""
    db = envelope(wav_path)
    i0 = 0 if a is None else int(a / FRAME)
    i1 = len(db) if b is None else int(b / FRAME)
    seg = db[i0:i1]
    voiced = seg[seg > np.percentile(seg, 60)]
    return float(np.mean(voiced)) if len(voiced) else float("nan")
