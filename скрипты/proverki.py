def v8_polya(d):
    """Субтитр влезает В СВОЁ ГНЕЗДО и не мельчает ниже читаемого.

    🔴 ПЕРЕПИСАНА. Первая версия делила ширину всего кадра (1080 × 0,86)
    на длину слова и спрашивала «остался ли кегль читаемым». На ролик она сказала
    «чисто», а в кадре опорное «ПРОТИВОПОЛОЖНЫЙ.» уехало за левый край: слово
    стояло в гнезде 8 шириной 686 px, а проверка мерила по 929. Проверка,
    которая меряет не ту коробку, меряет не тот дефект.

    Теперь берётся коробка того гнезда, которое реплике назначил `titry.py`, и
    та же оценка ширины прописной буквы, по какой ужимается компонент. Точную
    ширину строки меряет браузер (`Subtitles.tsx`, `measureText`) — здесь оценка
    сознательно ЗАВЫШЕНА по прописным: ворота должны срабатывать раньше, чем
    строка уедет, а не после.
    """
    beda = []
    for r in d["titry"]["реплики"]:
        j = r.get("гнездо")
        g = titry.GNEZDA[j] if isinstance(j, int) and j < len(titry.GNEZDA) else None
        if g is None:
            continue
        box = (g[1] - g[0]) * kadr.OUT_W
        base = g[3] * (kadr.OUT_W / 1080.0)
        opora = r.get("опора", -1)
        for i, w in enumerate(r["слова"]):
            # капсить или нет — решено в плане (`ЭКРАН.md` §1.6), здесь только читаем:
            # пересчитывать значит однажды разойтись с тем, что нарисовано.
            # У планов, собранных до ролик, поля нет — там остаётся прежний признак
            # (одна марка со смешанным регистром), чтобы старый ролик не начал
            # вдруг «ломать кадр» на перепрогоне
            kapsom = i == opora and r.get("опора_капсом",
                                          not titry.bez_kapsa(w["w"], None))
            razmer = base * (1.8 if i == opora else 1.0)
            dolya = ZNAK_KAPS if kapsom else ZNAK_STROCH
            nado = box / (dolya * max(len(w["w"]), 1))
            if nado < razmer * 0.999 and nado < KEGL_MIN:
                beda.append("слово «%s» (%d знаков) в гнезде %d влезает только в "
                            "%.0f px кегля — мельче порога %d"
                            % (w["w"], len(w["w"]), j, nado, KEGL_MIN))
    return beda


