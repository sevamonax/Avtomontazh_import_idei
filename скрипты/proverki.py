def v14_povtor_v_sborke(d):
    """🔑 ПОВТОР ИЩЕТСЯ В ГОТОВОМ ЗВУКЕ, А НЕ В РАСШИФРОВКЕ СЫРЬЯ.

    🔴 ЗАЧЕМ. В один ролик попали ДВА захода подряд: «в 24-м году Google
    DeepMind выпустили» и следом «в 2024 году Google DeepMind выпустили работу
    с названием…». Нашлось ухом на приёмке — тринадцать проверок молчали.

    Почему молчали. `dubli.py` и В2 ищут пересъёмку **сравнением текстов**, а
    текст берут из расшифровки по всплескам. У третьего, полного захода
    расшифровка потеряла начало и выдала его как «с названием «Языковые
    модели…» — с точки зрения текста это была ДРУГАЯ фраза, и повтора не
    существовало. Проверка, которая читает тот же испорченный текст, что и
    механизм, повторяет его ошибку слово в слово.

    Отсюда правило, уже дважды сработавшее в этом конвейере (В12 — замер
    нарисованного слоя, В13 — замер реального тона): **ворота обязаны смотреть
    на результат другими глазами, чем те, которыми его делали.** Здесь это
    сплошная расшифровка собранной дорожки: она слышит ролик так, как услышит
    зритель, и ей всё равно, что думала про эти секунды разметка сырья.

    Признак: цепочка из POVTOR_SLOV слов повторилась в пределах POVTOR_OKNO
    секунд. Порог не с потолка — четыре слова подряд в русской речи случайно
    не повторяются, а четырнадцать секунд это верхняя граница «переговорил
    фразу» (у `rech.py` то же число зовётся MAX_GAP и равно 22 с по сырью, где
    между заходами ещё стоят паузы; в сборке они вырезаны).
    🔴 ДВА ДЕФЕКТА, НАЙДЕННЫЕ 12.09.2026 НА ВТОРОЙ ПАЧКЕ.

    **Первый — проверка кричала на приём речи.** В ролик звучит «просто с
    расплывчатого пятна всё чётче-чётче-чётче-чётче…», в ролик — параллель «по
    поводу того, что мы видим, а не по поводу того, что мы предполагаем».
    Ни то, ни другое не пересъёмка: это ровно те фигуры, ради которых фразу и
    строят. Цепочка из одного повторённого слова исключена совсем.

    **Второй — проверка зацикливалась на себе.** Погасив найденный повтор, она
    записывала в «уже слышали» цепочки С ИХ ЖЕ ВРЕМЕНАМИ, начиная с текущей.
    На следующем шаге цепочка совпадала сама с собой, разница времён выходила
    нулевая, условие срабатывало — и так до конца ролика: **одна находка давала
    351 строку** вида «на 155.5 с повторён заход — он уже звучал на 155.5 с».
    Гейт с таким отчётом бесполезен: настоящая находка тонет в собственном эхе.
    Гашение теперь просто пропускает следующие позиции, ничего не записывая.
    """
    slova = d.get("sborka_slova")
    if slova is None:
        return ["сборки нет или whisper недоступен — проверка не проводилась"]
    beda, vidano, propuskat_do = [], {}, -1
    for i in range(len(slova) - POVTOR_SLOV + 1):
        cep = tuple(w for _, w in slova[i:i + POVTOR_SLOV])
        t = slova[i][0]
        if len(set(cep)) == 1:
            continue                      # «чётче-чётче-чётче» — нажим, не дубль
        if i <= propuskat_do:
            continue                      # гасим хвост уже названной находки
        bylo = vidano.get(cep)
        if bylo is not None and t - bylo <= POVTOR_OKNO:
            beda.append(u"на %.1f с повторён заход «%s» — он уже звучал на %.1f с"
                        % (t, u" ".join(cep), bylo))
            propuskat_do = i + POVTOR_SLOV * 3
            continue
        vidano[cep] = t
    return beda


