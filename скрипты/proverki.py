DUBLI_DOLYA = 0.5     # элемент говорит больше половины звучащего — он и есть субтитр


def v7_mehanizmB(d):
    """Элемент, ЗАБИРАЮЩИЙ РАБОТУ СУБТИТРА, гасит его на своё окно (`ЭКРАН.md` §0).

    Иначе текст на экране задваивается: и элемент, и субтитр говорят одно и то
    же разными кеглями.

    🔑 СПРАШИВАЕТСЯ РЕЗУЛЬТАТ, А НЕ ИМЯ ПРИЁМА. Первая версия освобождала от
    правила плашку канала — по названию, списком. 28.08 появилась сноска
    («Соломон Аш, 1951» — наше уточнение к оговорке в кадре), и проверка
    закричала на неё, хотя дублировать ей нечего: её текста в речи нет вообще.
    Список исключений по именам — это оговорка внутри правила, то есть дырка
    в воротах (`ЭКРАН.md` п.5).

    Меряется теперь доля: сколько из того, что звучит в окне элемента, элемент
    произносит сам. Врезка-принцип несёт реплику целиком — доля около единицы,
    гасить обязана. Плашка канала берёт «Ваш канал» из двадцати слов хвоста —
    доля 0,16, работу субтитра она не забирает. Сноска не совпадает с речью
    вовсе — доля ноль.
    """
    def golyy(x):
        return re.sub(r"[^0-9a-zа-яё%]+", "", x.lower().replace(u"ё", u"е"))

    beda = []
    for e in d["titry"]["элементы"]:
        svoi = golyy(e.get("текст") or "")
        rech = golyy(" ".join(w["w"] for r in d["titry"]["реплики"] for w in r["слова"]
                              if e["t"] - 0.01 <= w["s"] < e["конец"] + 0.01))
        if not svoi or not rech or svoi not in rech:
            continue
        if len(svoi) / float(len(rech)) < DUBLI_DOLYA:
            continue
        if not any(a <= e["t"] + 0.01 and b >= e["конец"] - 0.01
                   for a, b in d["titry"]["гасить"]):
            beda.append("элемент «%s» на %.2f говорит %.0f %% звучащего и не гасит "
                        "субтитр — текст задвоится"
                        % (e["приём"], e["t"], 100.0 * len(svoi) / len(rech)))
    return beda


