KRAY_PX = 8           # ближе этого к краю кадра — считаем, что строка уехала
ALFA_PORG = 40        # ниже — сглаживание края буквы, а не сама буква
ZALIVKA = 0.5         # альфа в среднем выше — это врезка во весь кадр, не строка
SCENA_ALFA_MIN = 0.02  # ниже — на месте сцены пусто: план есть, картинки нет


def zamer_sloya(pr, d):
    """Кадры слоя, на которых что-то стоит вплотную к краю кадра.

    Берём начало каждой реплики плюс середину — там строка уже нарисована
    целиком, а печать закончена. Врезку во весь кадр пропускаем: у неё альфа
    единица везде по замыслу.
    """
    sloi = os.path.join(pr.out, "слой.mov")
    if not os.path.exists(sloi):
        return None
    try:
        import numpy as np
    except ImportError:
        return None
    momenty = []
    for r in d["titry"]["реплики"]:
        a = r["слова"][0]["s"]
        b = r["слова"][-1]["e"]
        momenty.append(round(min(a + 0.25, (a + b) / 2.0), 2))
    momenty = sorted(set(m for m in momenty if m >= 0))
    out = []
    for t in momenty:
        p = subprocess.run(
            ["ffmpeg", "-v", "error", "-ss", "%.2f" % t, "-i", sloi, "-frames:v", "1",
             "-vf", "alphaextract,format=gray", "-f", "rawvideo", "-"],
            capture_output=True)
        if p.returncode != 0 or not p.stdout:
            continue
        w, h = kadr.OUT_W, kadr.OUT_H
        if len(p.stdout) < w * h:
            continue
        a = np.frombuffer(p.stdout[:w * h], dtype=np.uint8).reshape(h, w)
        if a.mean() / 255.0 > ZALIVKA:
            continue                      # врезка во весь кадр — так и задумано
        kray = []
        if a[:, :KRAY_PX].max() > ALFA_PORG:
            kray.append("левого")
        if a[:, -KRAY_PX:].max() > ALFA_PORG:
            kray.append("правого")
        if a[:KRAY_PX, :].max() > ALFA_PORG:
            kray.append("верхнего")
        if a[-KRAY_PX:, :].max() > ALFA_PORG:
            kray.append("нижнего")
        out.append((t, " и ".join(kray)))
    return out


def zamer_scen(pr, d):
    """Альфа слоя в середине каждой сцены инфографики: план есть — картинка есть?

    Отдельный замер, а не переиспользование `zamer_sloya`: тот ищет строки у
    края кадра и врезку во весь кадр СПЕЦИАЛЬНО пропускает, потому что у неё
    альфа единица везде. Сцена — как раз крупный элемент, и для неё вопрос
    обратный: нарисовано ли вообще хоть что-то.
    """
    sloi = os.path.join(pr.out, u"слой.mov")
    tit = d.get("titry") or {}
    sceny = [e for e in tit.get(u"элементы", []) if e.get(u"приём") == u"инфографика"]
    if not os.path.exists(sloi) or not sceny:
        return None
    try:
        import numpy as np
    except ImportError:
        return None
    out = {}
    for e in sceny:
        t0 = float(e.get("t", 0.0))
        t1 = float(e.get(u"конец", t0 + 1.0))
        seredina = (t0 + t1) / 2.0
        p = subprocess.run(
            ["ffmpeg", "-v", "error", "-ss", "%.2f" % seredina, "-i", sloi, "-frames:v", "1",
             "-vf", "alphaextract,format=gray", "-f", "rawvideo", "-"],
            capture_output=True)
        w, h = kadr.OUT_W, kadr.OUT_H
        if p.returncode != 0 or len(p.stdout or b"") < w * h:
            continue
        a = np.frombuffer(p.stdout[:w * h], dtype=np.uint8).reshape(h, w)
        out[round(t0, 2)] = float(a.mean()) / 255.0
    return out


def podsadka(d):
    """Подсаживаем в план заведомый дефект под каждую проверку и требуем крика."""
    proby = {
        "В2 брошенные заходы": lambda x: x["rech"][x["edl"]["дубль"]].insert(
            0, {"a": x["edl"]["куски"][0]["s"] + 0.1, "b": x["edl"]["куски"][0]["s"] + 0.4,
                "text": "подсадка", "norm": ["подсадка"], "слова": [], "брошен": True}),
        "В3 обрезанные слова": lambda x: x["runs_po"][x["edl"]["куски"][0]["idx"]].append(
            [x["edl"]["куски"][0]["s"] - 0.4, x["edl"]["куски"][0]["s"] + 0.4]),
        # Подсадка на В4 сдвигала начало куска на 2 с назад — и на серии
        # «Серия» промолчала: в этих двух секундах лежит выброшенный
        # заход, то есть настоящая речь, и тишины не появилось. Подсадка обязана
        # быть дефектом на ЛЮБОМ материале, поэтому теперь она делает кусок
        # немым: убирает все всплески, которые в него попадают.
        "В4 ритм пауз": lambda x: x["runs_po"].__setitem__(
            x["edl"]["куски"][1]["idx"],
            [r for r in x["runs_po"][x["edl"]["куски"][1]["idx"]]
             if not (r[1] > x["edl"]["куски"][1]["s"]
                     and r[0] < x["edl"]["куски"][1]["e"])]),
        "В5 линия глаз": lambda x: x["crops"]["план"].__setitem__(
            1, dict(x["crops"]["план"][1], py=x["crops"]["план"][0]["py"] + 0.2)),
        # f1=0.5 было числом под горизонтальный кадр 2160 px: там окно выходило
        # 1080 px и растягивалось вдвое. На вертикали 3840 то же 0,5 даёт ровно
        # 1920 — растяжения нет, и подсадка молчала. Считаем долю от геометрии.
        "В6 растяжение": lambda x: x["crops"]["план"].__setitem__(
            0, dict(x["crops"]["план"][0],
                    f1=kadr.OUT_H / (kadr.RASTYAG_MAX * 1.3) / float(kadr.H4K))),
        "В7 механизм Б": lambda x: x["titry"].__setitem__("гасить", []),
        "В8 поля": lambda x: x["titry"]["реплики"][0]["слова"].insert(
            0, {"w": "словокотороефизическиневлезаетниводнустроку", "s": 0.0, "e": 0.1}),
        "В10 лицо": lambda x: x["titry"]["лицо"].insert(
            0, {"t": 0.0, "конец": 1.0, "x0": 0.0, "x1": 1.0, "y0": 0.0, "y1": 1.0}),
        "В11 разнообразие": lambda x: [r.__setitem__("гнездо", 0)
                                       for r in x["titry"]["реплики"]],
        # Подсадка на В12 — не «сделать вид, что слоя нет» (это другой дефект,
        # и про него проверка говорит отдельной строкой), а кадр, на котором
        # строка касается края.
        "В12 слой в кадре": lambda x: (x.__setitem__("sloi", list(x.get("sloi") or []))
                                       or x["sloi"].append((0.0, "левого"))),
        # Подсадка на В16 — несуществующая сцена в раскадровке. Дефект годится на
        # ЛЮБОМ материале: набор сцен сверяется с компонентом, а не со словарём.
        u"В16 инфографика": lambda x: x.__setitem__(
            "cfg", dict(x.get("cfg") or {},
                        **{u"инфографика": [{u"сцена": u"подсадка_такой_сцены_нет"}]})),
        "В13 цензура": lambda x: x["cenzura"].append(
            {"s": 0.0, "e": 0.2, "доля_тона": 0.0, "rms": 0.0}),
    }
    print("ПОДСАДКА: каждая проверка обязана закричать на своём дефекте\n")
    # Выключенная настройкой проверка подсадку не проходит — и не должна
    # изображать, будто прошла. Молчание выключенного и молчание сломанного
    # выглядят одинаково, поэтому разница печатается словом: «выключена»
    # против «ПРОМОЛЧАЛА». Тот же принцип, по которому В12 без слоя честно
    # говорит, что замер не проводился.
    vykl = {u"В16 инфографика": (u"гейт.требовать_инфографику", False)}
    ok = True
    for name, fn in PROVERKI:
        if name not in proby:
            continue
        if name in vykl:
            klyuch, umolchanie = vykl[name]
            if not obshee.nastroyka(klyuch, umolchanie):
                print("  %-24s выключена настройкой «%s» — подсадка не проверялась"
                      % (name, klyuch))
                continue
        x = copy.deepcopy(d)
        proby[name](x)
        krik = fn(x)
        print("  %-24s %s" % (name, "закричала ✓" if krik else "❌ ПРОМОЛЧАЛА"))
        ok = ok and bool(krik)
    return ok


