# -*- coding: utf-8 -*-
"""Рез: из выбранного куска сырья — монтажный лист рилза.

    python rez.py --проект "ПРИМЕР" --кандидат 1
    python rez.py --проект "ПРИМЕР" --дубль 04 --от 12.4 --до 88.0

Выбрасывает: тишину между заходами, брошенные заходы (`rech.py`, `ЭКРАН.md` §8) и
паузы длиннее живого ритма. Смысл на этом проходе не трогается — ничего не
выбрасывается по содержанию (`README.md` шаг 2).

РИТМ ПАУЗ — ЗАМЕР, А НЕ ВКУС. Профиль снят `zamer.py` с принятого рилза
«ПРИМЕР» (опубликован, 1:52): медиана паузы 0,23 с, 90-я процентиль
0,35 с, максимум 0,42 с, речь занимает 94 % хронометража. До этого замера К5 в
вертикали был профилем длинного (медиана 0,25 с) — похоже, но не проверено.
"""
import os
import sys

BASE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BASE)
import obshee                                            # noqa: E402
import zvuk                                              # noqa: E402

# профиль вертикали, замер 04.08 по «ПРИМЕР.mp4»
MERGE_GAP = 0.45     # пауза короче — живая, оставляем как есть
SLOVO_GAP = 2.50     # до этой длины пауза слушается: в ней может лежать слово
SLOVO_DOLYA = 0.35   # и звучать она должна не меньше этой доли — иначе это вдох
PAUSE_KEEP = 0.25    # сколько молчит склейка: хвост куска + приступ следующего
MIN_HVOST = 0.07     # но с каждой стороны хоть столько — иначе срежется вдох
FPS = 30             # лист говорит в кадрах: ffmpeg всё равно округлит до них
EDGE_IN = 0.10       # воздух перед первым словом рилза
EDGE_OUT = 0.35      # и после последнего — иначе конец звучит обрубленным


def kuski_okna(pr, rech, syroe, idx, ot, do):
    """Куски одного окна одного дубля. Возвращает список и что выброшено."""
    wav = pr.wav_path(idx)
    db = zvuk.envelope(wav)

    bursts = [b for b in rech[idx] if b["b"] > ot and b["a"] < do]
    if not bursts:
        raise SystemExit("в этом окне нет ни одного всплеска")

    # ❗Соседи по СЫРЬЮ, а не по листу. Граница куска, дотянутая до края слова
    # или раздвинутая под паузу, не имеет права заехать на выброшенный заход:
    # гейт поймал ровно это — конец «Привет!» наезжал на брошенное «Меня зовут
    # Имя Фамилия.», и в ролик осталось бы полслога чужого дубля.
    vse = sorted(syroe[idx], key=lambda b: b["a"])
    runs_all = zvuk.speech_runs(wav)      # где на самом деле звучит речь

    def sosedi(t0, t1):
        levo = max([b["b"] for b in vse if b["b"] <= t0 + 0.01] or [0.0])
        pravo = min([b["a"] for b in vse if b["a"] >= t1 - 0.01] or [1e9])
        return levo, pravo

    kuski, vyrezano = [], []
    for k, b in enumerate(bursts):
        a = max(ot, b["a"])
        e = min(do, b["b"])
        levo, pravo = sosedi(a, e)
        # границы дотягиваются до настоящих краёв слов: порог, которым ищут речь,
        # срезает тихие приступы и хвосты («катастрофа» теряла своё «-фа»)
        a = max(zvuk.expand(a, db, forward=False), levo + 0.02)
        e = min(zvuk.expand(e, db, forward=True), pravo - 0.02)
        if k == 0:
            a = max(0.0, a - EDGE_IN, levo + 0.02)
        if k == len(bursts) - 1:
            e = min(e + EDGE_OUT, pravo - 0.02)
        b["_levo"], b["_pravo"] = levo, pravo
        kuski.append({"idx": idx, "s": round(a, 3), "e": round(e, 3),
                      "текст": b["text"], "слова": b["слова"],
                      "_levo": levo, "_pravo": pravo,
                      # края слова по огибающей — ниже их резать нельзя
                      "_словоS": round(a, 3), "_словоE": round(e, 3)})

    # всё, что выброшено `dubli.py`, попадает в отчёт: решение должно быть видно
    ostavleno = {round(b["a"], 2) for b in bursts}
    for b in syroe[idx]:
        if b["b"] > ot and b["a"] < do and round(b["a"], 2) not in ostavleno:
            vyrezano.append({"s": b["a"], "e": b["b"], "текст": b["text"],
                             "почему": "брошенный заход" if b.get("брошен")
                             else "пересъёмка / огрызок / мусор"})

    return kuski, vyrezano


def sobrat(pr, okna):
    """Монтажный лист из одного или нескольких окон — возможно, разных файлов.

    Ролик серии может быть снят В ДВА ФАЙЛА: на одном из роликов человек
    оборвал фразу на середине, выключил камеру и продолжил ровно с неё. Пока
    лист умел один дубль, такой ролик нельзя было собрать вообще.

    Склейка соседей идёт ТОЛЬКО внутри одного дубля: между файлами склеивать
    нечего — там смена камеры, а не живая пауза. Ритм паузы на стыке файлов
    считается теми же формулами, но по огибающей своего дубля.
    """
    rech = pr.load("chisto.json")
    syroe = pr.load("rech.json")
    kuski, vyrezano, sohraneno = [], [], []
    for idx, ot, do, rezhim in okna:
        if rezhim == "целиком":
            # 🔑 ОКНО «ЦЕЛИКОМ» — кусок сырья без реза внутренних пауз.
            #
            # Открывашка ролик — стук мелодии кулаком по столу. Слов в ней нет,
            # поэтому обычный путь её теряет дважды: `dubli.py` выбрасывает
            # всплески без текста как мусор, а рез пауз, даже если их вернуть,
            # переставил бы удары — то есть переписал бы мелодию. Ритм здесь и
            # есть содержание, и трогать его нельзя.
            #
            # Такому окну не нужны ни расшифровка, ни границы по огибающей: оно
            # приходит парой чисел и уходит в лист одним куском.
            kuski.append({"idx": idx, "s": round(ot, 3), "e": round(do, 3),
                          "текст": "", "слова": [], "целиком": True,
                          "_levo": 0.0, "_pravo": 1e9})
            continue
        k, v = kuski_okna(pr, rech, syroe, idx, ot, do)
        kuski += k
        vyrezano += v
    if not kuski:
        raise SystemExit("ни одного куска ни в одном окне")
    runs_po = {i: zvuk.speech_runs(pr.wav_path(i)) for i in {k["idx"] for k in kuski}}

    # склейка соседей, между которыми пауза живая
    #
    # 🔑 ЗАЗОР ОБЯЗАН БЫТЬ НЕОТРИЦАТЕЛЬНЫМ. Проверка «зазор не больше MERGE_GAP»
    # молча считала соседями куски, которые в сырье идут НАЗАД: окна больше не
    # обязаны стоять по времени — хук ролик вынут из середины
    # и поставлен первым. На таком стыке разность
    # отрицательная, условие срабатывало, и следующий кусок вливался в
    # предыдущий: конец уезжал в прошлое, длительность выходила отрицательной и
    # округлялась до одного кадра. Тезис ролика превращался в 0,03 с, и ни одна
    # проверка этого не видела — лист выглядел нормальным (`ЭКРАН.md` §4: ворота
    # обязаны проверять результат, а не факт вызова).
    sklein = [kuski[0]]
    for k in kuski[1:]:
        zazor = k["s"] - sklein[-1]["e"]
        # ❗Соседство проверяется по НАЧАЛУ куска, а не по зазору. Первая версия
        # этой правки требовала «зазор ≥ 0» — и заодно запретила склейку кусков,
        # которые слегка налезают друг на друга: `expand` дотягивает обе границы
        # до краёв слов, и на быстрой речи конец предыдущего заходит за начало
        # следующего на сотые доли. Такие куски переставали склеиваться, между
        # ними вставлялась подрезка паузы — и на одном из роликов вышло пять огрызков подряд
        # вместо одной фразы, «отвратительный монтаж с обрывом слов».
        # Назад по сырью прыгает только переставленное окно, и прыгает далеко.
        svoy = (k["idx"] == sklein[-1]["idx"] and not k.get("целиком")
                and not sklein[-1].get("целиком") and k["s"] >= sklein[-1]["s"])
        # 🔑 В ПАУЗЕ МОЖЕТ ЖИТЬ СЛОВО. Порог всплесков груб (на 22 дБ ниже речи),
        # и тихое слово между двумя всплесками не попадает ни в один — а рез
        # ужимает эту «паузу» до 0,25 с и слово пропадает. Поэтому перед резом
        # промежуток слушается чувствительным порогом: есть звук — куски
        # склеиваются, то есть промежуток остаётся как записан. Верхняя граница
        # нужна, чтобы шорох в настоящей паузе не сохранял три секунды тишины.
        slovo = (svoy and MERGE_GAP < zazor <= SLOVO_GAP
                 and zvuk.dolya_zvuka(pr.wav_path(k["idx"]),
                                      sklein[-1]["e"], k["s"]) >= SLOVO_DOLYA)
        if svoy and (zazor <= MERGE_GAP or slovo):
            if slovo:
                sohraneno.append((sklein[-1]["e"], k["s"],
                                  zvuk.dolya_zvuka(pr.wav_path(k["idx"]),
                                                   sklein[-1]["e"], k["s"])))
            sklein[-1]["e"] = k["e"]
            sklein[-1]["_pravo"] = k["_pravo"]      # правый сосед теперь чужой
            sklein[-1]["_словоE"] = k["_словоE"]
            sklein[-1]["текст"] += " " + k["текст"]
            sklein[-1]["слова"] += k["слова"]
        else:
            vyrezano.append({"s": sklein[-1]["e"], "e": k["s"],
                             "текст": "", "почему": "пауза %.2f с → %.2f"
                             % (k["s"] - sklein[-1]["e"], PAUSE_KEEP)})
            sklein.append(k)

    # 🔑 ПАУЗА ЗАДАЁТСЯ ЗАМЕРОМ СЛЫШИМОЙ ТИШИНЫ, А НЕ ЗАЗОРОМ В ПЛАНЕ.
    #
    # Куски в ролик стоят встык, поэтому «зазор между ними» всегда нулевой, а
    # молчит зритель ровно столько, сколько намолчали ХВОСТ предыдущего куска и
    # ПРИСТУП следующего. Первая версия раздвигала куски навстречу паузе на
    # PAUSE_KEEP/2 и считала, что этим задала ритм; на готовом файле вышло
    # 0,84 с на склейке при цели 0,25, и проверка В4 этого не видела, потому что
    # смотрела в план. Вставлять синтетическую тишину нельзя — это застывший
    # кадр посреди речи; значит, границы надо подрезать до цели.
    #
    # Подрезаем пропорционально и НИКОГДА внутрь речи: с каждой стороны
    # остаётся хотя бы MIN_HVOST, иначе срежется тихий приступ слова и вдох.
    def krai(k):
        vn = [r for r in runs_po[k["idx"]] if r[1] > k["s"] and r[0] < k["e"]]
        if not vn:
            return 0.0, 0.0
        return max(0.0, vn[0][0] - k["s"]), max(0.0, k["e"] - vn[-1][1])

    for i in range(len(sklein) - 1):
        # Границы окна «целиком» назначены рукой и подрезке не подлежат: там
        # ритм, а не речь.
        if sklein[i].get("целиком") or sklein[i + 1].get("целиком"):
            continue
        _, hvost = krai(sklein[i])
        pristup, _ = krai(sklein[i + 1])
        doly = hvost + pristup
        # сколько тишины положено каждой стороне: по MIN_HVOST обеим, остаток
        # делим в той пропорции, в какой они молчали сами
        ostatok = max(0.0, PAUSE_KEEP - 2 * MIN_HVOST)
        want_h = MIN_HVOST + (ostatok * hvost / doly if doly > 0 else ostatok / 2)
        want_p = MIN_HVOST + (ostatok * pristup / doly if doly > 0 else ostatok / 2)
        # правило работает в обе стороны: длинную тишину режем, короткую
        # дотягиваем. Дотягивать важно не меньше: рез в 20 мс от первого звука
        # слышен как обрубленный приступ, а не как быстрый монтаж
        # 🔑 РИТМ УКОРАЧИВАЕТ ТИШИНУ, А НЕ РЕЧЬ. Подгон паузы двигал границы
        # свободно и на одном из роликов срезал хвост слова «шрифтом»: `expand` честно нашёл
        # край слова на 175.38, а подгон вернул конец куска на 175.24 — ровно
        # в середину затухающего «-ом». Дефект того же рода, что `ЭКРАН.md` §8
        # («катастрофа» теряла «-фа»), только источник другой: там граница не
        # дотягивалась, здесь дотянутую границу отняли обратно. Край, найденный
        # по огибающей, теперь нижняя граница подгона: молчание сжимаем,
        # звучащее не трогаем.
        e = min(sklein[i]["e"] + (want_h - hvost), sklein[i]["_pravo"] - 0.02)
        e = max(e, sklein[i]["_словоE"])
        s = max(sklein[i + 1]["s"] - (want_p - pristup), sklein[i + 1]["_levo"] + 0.02)
        s = min(s, sklein[i + 1]["_словоS"])
        sklein[i]["e"] = round(e, 3)
        sklein[i + 1]["s"] = round(s, 3)

    # 🔑 ДЛИТЕЛЬНОСТЬ КУСКА — ЦЕЛОЕ ЧИСЛО КАДРОВ. ffmpeg режет по кадрам, и на
    # 23 кусках округление вверх набежало на 0,28 с: гейт В1 поймал расхождение
    # листа и файла. Раз лист — источник времени для субтитров, он обязан
    # говорить в тех же единицах, в которых работает рендер.
    t = 0.0
    for k in sklein:
        k.pop("_levo", None)
        k.pop("_pravo", None)
        k.pop("_словоS", None)
        k.pop("_словоE", None)
        kadrov = max(1, int(round((k["e"] - k["s"]) * FPS)))
        k["e"] = round(k["s"] + kadrov / float(FPS), 3)
        k["t"] = round(t, 3)
        k["длит"] = round(kadrov / float(FPS), 3)
        t += k["длит"]
    return sklein, vyrezano, round(t, 3), sohraneno


def mmss(t):
    return "%d:%05.2f" % (int(t // 60), t % 60)


def main():
    pr, a = obshee.argi((["--кандидат"], {"dest": "kand", "type": int, "default": None}),
                        (["--дубль"], {"dest": "idx", "default": None}),
                        (["--от"], {"dest": "ot", "type": float, "default": None}),
                        (["--до"], {"dest": "do", "type": float, "default": None}),
                        (["--окна"], {"dest": "okna", "default": None}))
    if a.okna:
        # «01:35-176,02:0-301» — дубль, начало и конец окна в секундах сырья
        okna = []
        for ch in a.okna.split(","):
            ch = ch.strip()
            rezhim = "речь"
            if "/" in ch:
                ch, rezhim = ch.rsplit("/", 1)
                rezhim = rezhim.strip()
                if rezhim != "целиком":
                    raise SystemExit("режим окна бывает только «целиком», пришло «%s»" % rezhim)
            idx, rng = ch.strip().split(":")
            ot, do = rng.split("-")
            okna.append((idx.strip(), float(ot), float(do), rezhim))
    elif a.kand:
        c = pr.load("kandidaty.json")[a.kand - 1]
        okna = [(c["idx"], c["s"], c["e"], "речь")]
    elif a.idx is not None:
        okna = [(a.idx, a.ot, a.do, "речь")]
    else:
        raise SystemExit("нужен --окна «01:от-до,02:от-до», --кандидат N или --дубль/--от/--до")

    kuski, vyrezano, vsego, sohraneno = sobrat(pr, okna)
    pr.save("edl.json", {"дубль": okna[0][0],
                         "окна": [[i, o, d, r] for i, o, d, r in okna],
                         "от": okna[0][1], "до": okna[-1][2],
                         "куски": kuski, "всего": vsego})

    rechi = sum(k["длит"] for k in kuski)
    lines = ["# МОНТАЖНЫЙ ЛИСТ — «%s»\n" % pr.name,
             "Окна: %s. **Итог %s** (%d кусков, речь %.0f %%)."
             % (" · ".join("дубль %s %s–%s%s" % (i, mmss(o), mmss(d),
                                                " целиком" if r == "целиком" else "")
                           for i, o, d, r in okna),
                mmss(vsego), len(kuski), 100 * rechi / vsego),
             "",
             "Ритм пауз — замер по принятому рилзу. На склейке молчит %.2f с:",
             "хвост куска плюс приступ следующего, каждому не меньше 0,07 с.",
             "Медиана твоего же ролика — 0,23 с.", "",
             "| # | В сырье | На таймлайне | Длит. | Речь |",
             "|---|---|---|---|---|"]
    lines[3] = lines[3] % PAUSE_KEEP
    for i, k in enumerate(kuski, 1):
        lines.append("| %d | %s %s–%s | %s | %.2f с | %s |"
                     % (i, k["idx"], mmss(k["s"]), mmss(k["e"]), mmss(k["t"]), k["длит"],
                        k["текст"][:80]))
    if sohraneno:
        lines += ["", "## Паузы, сохранённые как записаны", "",
                  "В промежутке услышан звук ниже порога всплесков — значит там слово,",
                  "которое рез бы срезал. Промежуток оставлен нетронутым.", "",
                  "| В сырье | Длина | Звучит |", "|---|---|---|"]
        for a0, b0, d in sohraneno:
            lines.append("| %s–%s | %.2f с | %.0f %% |" % (mmss(a0), mmss(b0), b0 - a0, 100 * d))
    lines += ["", "## Что вырезано", "",
              "| В сырье | Почему | Текст |", "|---|---|---|"]
    for v in vyrezano:
        lines.append("| %s–%s | %s | %s |"
                     % (mmss(v["s"]), mmss(v["e"]), v["почему"], v["текст"][:70]))
    pr.text("ЛИСТ.md", "\n".join(lines) + "\n")

    print("кусков %d · итог %s · речь %.0f %%" % (len(kuski), mmss(vsego), 100 * rechi / vsego))
    print("вырезано мест: %d · пауз сохранено (в них слово): %d"
          % (len(vyrezano), len(sohraneno)))
    print("лист: %s" % pr.path("ЛИСТ.md"))


if __name__ == "__main__":
    main()
