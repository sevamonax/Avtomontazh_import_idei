def golo(w):
    return re.sub(r"[^а-яa-z0-9-]", "", w.lower().replace("ё", "е"))


def cifra(w):
    return bool(re.search(r"\d", w))


def slova_taimlainа(edl):
    """Слова монтажного листа во времени сборки, а не сырья."""
    out = []
    for k in edl["куски"]:
        for w in k["слова"]:
            s = k["t"] + max(0.0, w["s"] - k["s"])
            e = k["t"] + min(k["e"] - k["s"], w["e"] - k["s"])
            if e <= s:
                e = s + 0.08
            if s > k["t"] + (k["e"] - k["s"]) + 0.01:
                continue
            out.append({"w": w["w"], "s": round(s, 3), "e": round(e, 3)})
    # 🔑 ПОРЯДОК СЛОВ БЕРЁТСЯ ИЗ МОНТАЖА, А НЕ ИЗ ПЕРЕСЧИТАННЫХ ВРЕМЁН.
    #
    # Здесь стояла общая сортировка по времени. Пока кусок был один всплеск, она
    # ничего не меняла. После того как склейка стала собирать в кусок несколько
    # всплесков, их пословные времена — посчитанные в разных упакованных окнах —
    # начали перекрываться, и сортировка меняла слова местами: в субтитре ролике
    # вышло «есть там вообще смысл ИЛИ ОТСЮДА нет» вместо «смысл отсюда или нет».
    # Речь идёт в том порядке, в каком стоят куски и всплески внутри них; время
    # слова — это оценка, и спорить с порядком монтажа она не вправе.
    # Перекрытия разводим, сохраняя порядок.
    for i in range(len(out) - 1):
        if out[i + 1]["s"] < out[i]["s"]:
            out[i + 1]["s"] = out[i]["s"]
        if out[i]["e"] > out[i + 1]["s"]:
            out[i]["e"] = round(max(out[i]["s"] + 0.06, out[i + 1]["s"] - 0.01), 3)
        if out[i + 1]["e"] <= out[i + 1]["s"]:
            out[i + 1]["e"] = round(out[i + 1]["s"] + 0.08, 3)
    return out


def sklеit_pechat(kuchki):
    """Печатающаяся реплика забирает продолжение фразы.

    Приёмка ролике: «анимация с Сергеем Брином не доведена до конца, она исчезает с
    экрана быстрее, чем её можно прочитать». Причина в паре: реплика «Да ещё и
    Сергей Брин,» кончается запятой, то есть мысль в ней не закончена, а набор
    занимает всю её длину — целиком строка стоит доли секунды и уступает место
    следующей.

    Правило: если реплика кончается запятой и вместе со следующей укладывается
    в порог тезиса, они склеиваются в одну. Печать тогда набирает мысль
    целиком, а не её первую половину. Сам порог печати (`ЭКРАН.md` §1.3) не трогается.
    """
    out, sklеeno, i = [], set(), 0
    while i < len(kuchki):
        cur = kuchki[i]
        tekst = " ".join(w["w"] for w in cur)
        if (i + 1 < len(kuchki) and re.search(r"[,;:]$", tekst)
                and len(cur) + len(kuchki[i + 1]) <= TEZIS_SLOV
                and kuchki[i + 1][0]["s"] - cur[-1]["e"] < 0.45):
            cur = cur + kuchki[i + 1]
            i += 1
            sklеeno.add(len(out))
        out.append(cur)
        i += 1
    return out, sklеeno


def razbit(words):
    """Реплики: по знаку препинания, паузе > 0.3 с или длине. Числовой ряд не рвём."""
    out, cur = [], []
    for i, w in enumerate(words):
        nxt = words[i + 1] if i + 1 < len(words) else None
        cur.append(w)
        if cifra(w["w"]) and nxt and cifra(nxt["w"]):
            continue
        tochka = re.search(r"[.!?…]$", w["w"])
        zapyataya = re.search(r"[,;:]$", w["w"])
        pauza = (nxt["s"] - w["e"]) if nxt else 99.0
        if tochka or pauza > BREAK_GAP or (zapyataya and len(cur) >= 2) or len(cur) >= MAX_SLOV:
            out.append(cur)
            cur = []
    if cur:
        out.append(cur)
    return out


OPORA_MIN = 6         # короче — слово не тянет на смысловой центр
OPORA_SHAG = 3        # опора не чаще, чем раз в столько реплик


def opornoe(ws, vidano, s_proshloi):
    """Одно опорное слово реплики (`ЭКРАН.md` §1.6). −1 — опоры нет.

    Два ограничения, без которых приём исчезает:
      · **слово должно звучать впервые.** Крупным делается новое понятие, а не
        десятое повторение слова «нейросети»;
      · **не чаще раза в три реплики.** Первая версия ставила опору в 98 из 102
        реплик — если крупным становится каждое второе слово, крупных слов нет.
        Это та же плотность, что в `README.md` шаг 4 для графики: приём считается
        приёмом, пока он редкий.
    """
    if s_proshloi < OPORA_SHAG:
        return -1
    best, dlina = -1, 0
    for i, w in enumerate(ws):
        g = golo(w["w"])
        if len(g) < OPORA_MIN or g in SLUZHEBNYE or cifra(w["w"]) or g in vidano:
            continue
        if len(g) > dlina:
            best, dlina = i, len(g)
    return best


def znak_repliki(ws, tekst, sled_teksty, opora, sklеena=False):
    """Знак-маркер по СМЫСЛУ реплики (`ЭКРАН.md` §1.5), а не по её номеру.

    ⚠️ Ряд отрицаний ищется НЕ внутри одной реплики. Разбивка рвёт его на куски
    («не технарь,» / «не айтишник,» / «не программист.»), и правило «два `не` в
    строке» не срабатывает ни разу. Смотрим на реплику вместе с соседними.
    """
    nizhe = tekst.lower()
    vmeste = " ".join([nizhe] + [t.lower() for t in sled_teksty])
    # ✕ — это «так не надо» (`ЭКРАН.md` §1.5), то есть ЗАПРЕТ, а не любое отрицание.
    # На проверке кадра он встал вокруг «что я совсем не технарь» — человек
    # рассказывает о себе, а знак читается как «так делать нельзя».
    if re.search(r"\bне (надо|стоит|нужно|делай|делайте)\b|\bнельзя\b", nizhe):
        return "✕"
    # ряд из трёх отрицаний подряд — это перечисление, у него свой знак
    if len(re.findall(r"\bне\s+[а-яё]", vmeste)) >= 3 and re.search(r"\bне\s+[а-яё]", nizhe):
        return "•"
    if re.search(VVODNOE, nizhe):
        return "("
    if re.search(VYVOD, nizhe):
        return "<<"
    # ⚠️ Запятые считаются признаком перечисления только на НЕсклеенной реплике.
    # После склейки внутрь попадает продолжение фразы, и
    # запятых там две по устройству: «Да ещё и Сергей Брин, основатель Google,»
    # получал `•` и превращался в список из одного пункта.
    if tekst.count(",") >= 2 and not sklеena:
        return "•"
    # `< СЛОВО >` — акцент вместо знака-скобки: только на короткой реплике,
    # у которой есть опора. Крупное слово в рамке — уже два приёма на одном
    # месте, поэтому больше ничего к ней не добавляется.
    if opora >= 0 and len(ws) <= 3:
        return "<"
    return None


DOLYA_PECHATI = 0.20      # доля реплик под печать; ниже — почему именно она
DOLYA_POSLOVU = 0.14      # и столько же под проявление по слову — вторая анимация


def animaciya(ws, znak, tekst, prev_pauza, sklеena=False):
    """`ЭКРАН.md` §1.3: печать — маркер авторской мысли, а не способ подать расшифровку.

    Здесь решается только ПРИГОДНОСТЬ места; сколько их взять — в `pechat_dolei`.
    """
    if znak in ("•", "✕"):
        return "по-слову"            # перечисление проявляется по мере речи
    if len(ws) >= 3 and len(ws) <= TEZIS_SLOV and re.search(r"[.!?,]$", tekst):
        return "печать?"             # кандидат, решение — по доле
    if len(ws) >= 4:
        return "по-слову?"           # длинную реплику можно проявлять по слову
    return "рез"


def pechat_dolei(repliki):
    """Печать ставится ДОЛЕЙ от ролика, а не порогом паузы.

    🔴 ПОЧЕМУ ПЕРЕПИСАНО (замер 27.08.2026, замечание «графика однообразна»).
    Пропорции печати не было записано нигде — ни в `ЭКРАН.md` §1.3, ни в `ЭКРАН.md` §0. Порог «пауза
    перед репликой ≥ 0,22 с» её задавал молча, и доля гуляла от материала:
    6 % на одном из роликов, **2 % на одном из роликов** (одна реплика на весь ролик), 6 % на «Посте
    знакомство». То есть приём то есть, то нет, и от ролика это не зависит.

    Доля была назначена и записана: 11 % реплик, примерно каждая девятая.
    Место выбирается не подряд, а по силе: из пригодных берутся те, перед
    которыми пауза длиннее — там, где мысль и так отбита голосом.

    🔴 ВТОРАЯ ПРАВКА 12.09.2026, замечание : «мало анимаций появления
    текста, надо увеличить и разнообразить». Доля печати была 11 % — примерно
    каждая девятая реплика, и это единственная анимация на ролик: «по-слову»
    включалось только на перечислениях со знаком, то есть почти никогда
    (в четырёх роликах второй пачки — один раз на все 257 реплик).

    Стало две назначенные доли: **печать 20 %** и **по слову 14 %**. Обе
    выбираются по силе места (пауза перед репликой), и **подряд две
    анимированные не ставятся** — иначе приём превращается в режим, а режим
    перестаёт читаться как акцент.
    """
    def vybrat(metka, dolya, zanyato):
        kand = [i for i, r in enumerate(repliki) if r["анимация"] == metka]
        if not kand:
            return set()
        skolko = max(1, int(round(len(repliki) * dolya)))
        kand.sort(key=lambda i: -repliki[i]["пауза"])
        vzyato = set()
        for i in kand:
            if len(vzyato) >= skolko:
                break
            if (i - 1) in zanyato or (i + 1) in zanyato:
                continue               # подряд — это режим, а не приём
            vzyato.add(i)
            zanyato.add(i)
        return vzyato

    zanyato = set()
    pech = vybrat("печать?", DOLYA_PECHATI, zanyato)
    poslovu = vybrat("по-слову?", DOLYA_POSLOVU, zanyato)
    for i, r in enumerate(repliki):
        if r["анимация"] == "печать?":
            r["анимация"] = "печать" if i in pech else "рез"
        elif r["анимация"] == "по-слову?":
            r["анимация"] = "по-слову" if i in poslovu else "рез"
        r.pop("пауза", None)
    return len(pech)


# Гнёзда субтитра — те же числа, что в `Subtitles.tsx` и в `proverki.py`.
# Дублирование осознанное: замер обязан считать по числам рендера.
GNEZDA = [
    (0.065, 0.60, 0.555, 50), (0.12, 0.88, 0.605, 52),
    (0.42, 0.935, 0.545, 48), (0.065, 0.62, 0.655, 46),
    (0.065, 0.56, 0.215, 46), (0.46, 0.935, 0.195, 52),
    (0.065, 0.58, 0.455, 50), (0.16, 0.84, 0.285, 48),
    (0.30, 0.935, 0.700, 46), (0.065, 0.50, 0.510, 48),
]
VERHNIE = {4, 5, 7}          # гнёзда выше корпуса: там обычно лицо
UGOL_MAX_SLOV = 3            # `ЭКРАН.md` §1.1: наверх — только короткая реплика
GNEZDO_NE_CHASHCHE = 3       # то же гнездо не чаще, чем через столько реплик

# Доли кегля на знак — ЗАМЕР по альфе собранного слоя (ролик, 28.08.2026): у Prata
# строчная ~0,58 кегля, прописная ~0,79. Живут здесь, а не в `proverki.py`,
# потому что теперь по ним считают двое: гнездо выбирается с оглядкой на них, и
# В8 ими же проверяет результат. Два списка одного правила разъезжаются.
ZNAK_STROCH = 0.58
ZNAK_KAPS = 0.79
KEGL_MIN = 44                # мельче — субтитр перестаёт читаться с телефона


def bez_kapsa(slovo, pred):
    """`ЭКРАН.md` §1.6 и `ЭКРАН.md` §1.6: опорное слово капсом — но не имя собственное.

    `pred` — предыдущее слово ролика (None, если это самое первое).

    Два признака, оба механические:
      · смешанный регистр — марка (ChatGPT, YouTube, iPhone);
      · заглавная, перед которой фраза НЕ кончилась. В русском тексте это имя
        собственное: «Импорт», «Google», «Аш».

    ⚠️ Граница берётся по ФРАЗЕ, а не по реплике. Первая версия правила (ролик)
    спрашивала «заглавная не в начале реплики» и на том же ролик промахнулась:
    реплика 67 начинается ровно с «Импорт», потому что разбивка режет фразу
    «Залетай ко мне на канал „Ваш канал“» пополам. Реплика — это единица
    показа, а не предложения; про имя собственное она ничего не знает.

    Решение считается ЗДЕСЬ и уходит в план полем `опора_капсом`: рисует
    компонент, ширину меряет В8, показывает СЛОЙ.md — трое считать одно и то же
    не должны, они разъедутся (`ЭКРАН.md` §9 — ровно про это).
    """
    bukvy = re.sub(u"^[^0-9A-Za-zА-Яа-яЁё]+", u"", slovo)
    if re.search(u"[a-zа-яё].*[A-ZА-ЯЁ]", bukvy):
        return True
    if not re.match(u"^[A-ZА-ЯЁ][a-zа-яё]", bukvy or u" "):
        return False
    if pred is None:
        return False
    return not re.search(u"[.!?…][»\"')\\]]?\\s*$", pred)


def _vlezaet_v_gnezdo(g, r):
    """Влезает ли реплика в это гнездо, не мельчая ниже читаемого.

    🔴 ДОБАВЛЕНО НА ролик. Гнездо выбиралось по одному признаку — не закрыто ли оно
    лицом. Ширина гнезда в выбор не входила вообще, и реплику «было бы
    РЕЦЕНЗИРОВАНИЯ.» механизм поставил в гнездо 9 — самое узкое из десяти
    (470 px). Опорное слово там ужималось до 40 px при пороге 44: акцент,
    который делает слово МЕЛЬЧЕ обычного текста, — это уже не акцент.

    В8 такой случай ловила и раньше, но ловила ПОСЛЕ: гейт кричал, а починить
    его можно было только руками — переписав речь или переназначив гнездо.
    Правило: что механизм может решить сам, он решает сам.
    """
    box = (g[1] - g[0]) * 1080.0
    opora = r.get(u"опора", -1)
    for i, w in enumerate(r[u"слова"]):
        kapsom = i == opora and r.get(u"опора_капсом", True)
        razmer = g[3] * (1.8 if i == opora else 1.0)
        nado = box / ((ZNAK_KAPS if kapsom else ZNAK_STROCH) * max(len(w[u"w"]), 1))
        if nado < razmer * 0.999 and nado < KEGL_MIN:
            return False
    return True


def _peresekaet(g, l, strok):
    if not l:
        return False
    x0, x1, y, kegl = g
    y1 = y + (kegl * 1.25 * strok) / 1920.0
    return x0 < l["x1"] and x1 > l["x0"] and y < l["y1"] and y1 > l["y0"]


def gnezda_planom(repliki, lica):
    """Гнездо каждой реплики — решение механизма, а не «первое свободное».

    🔴 ПОЧЕМУ ПЕРЕПИСАНО (замер 27.08.2026). `ЭКРАН.md` §1.1 требует восемь гнёзд, включая
    верхние. Замер по трём собранным роликам показал, что фактически работают
    ЧЕТЫРЕ, и все в корпусе, а распределение внутри них перекошено: «корпус
    слева» 44 %, «корпус справа» 2,6 %, верхние гнёзда — 0,0 % во всех трёх,
    включая принятый «ПРИМЕР».

    Две причины, обе механические:
      · компонент брал ПЕРВОЕ свободное гнездо, начиная со своего по кругу.
        Свободны всегда одни и те же, значит и берутся всегда одни и те же;
      · коробка лица в вертикали занимает x 0,14–0,86 и y 0,05–0,55, то есть
        верхнюю половину кадра. Верхние гнёзда физически заняты почти всегда —
        на среднем плане они и не могут освободиться.

    Отсюда правило: берём не первое свободное, а то из свободных, которое
    дольше всех не использовалось. Верхние гнёзда при этом не выключены — они
    выигрывают там, где лицо мелкое (общий план, кадр целиком), и правило `ЭКРАН.md` §1.1
    «наверх только короткая реплика без чисел и через одну» проверяется здесь.
    """
    out, kogda = [], {}
    prev_verh = False
    for ri, r in enumerate(repliki):
        t0 = r["слова"][0]["s"]
        l = next((x for x in lica if x["t"] <= t0 < x["конец"]), None)
        strok = 2 if len(r["слова"]) > 3 else 1
        est_cifra = any(cifra(w["w"]) for w in r["слова"])
        svobodnye, uzkie = [], []
        for j, g in enumerate(GNEZDA):
            if _peresekaet(g, l, strok):
                continue
            if j in VERHNIE:
                # `ЭКРАН.md` §1.1: наверх — только короткая реплика без чисел и через одну
                if prev_verh or est_cifra or len(r["слова"]) > UGOL_MAX_SLOV:
                    continue
                # 🔑 ПОКА ВИСИТ ЗАГОЛОВОК, ВЕРХ ЗАНЯТ. Шапка живёт 0–4,6 с в
                # левом верхнем углу (`ЭКРАН.md` §1.2), и верхнее гнездо в это время
                # накладывается на неё: на одном из роликов гейт поймал наложение на 3,2 с.
                # Проверка это видела, а расстановка — нет: два механизма
                # занимали одно место, не зная друг о друге.
                if t0 < ZAGOLOVOK_S:
                    continue
            # гнездо, в которое реплика влезает только мельче читаемого, —
            # не свободное, а тесное. Берём такие, только если других нет
            if not _vlezaet_v_gnezdo(g, r):
                uzkie.append(j)
                continue
            svobodnye.append(j)
        if not svobodnye:
            # все просторные заняты лицом — идём в тесные, а не в первое подряд;
            # если и тех нет, остаётся прежний запасной ход, его ловит В10
            svobodnye = uzkie or [ri % len(GNEZDA)]
        # дольше всех не использованное; при равенстве — по порядку
        j = min(svobodnye, key=lambda k: (kogda.get(k, -99), k))
        if len(svobodnye) > 1 and ri - kogda.get(j, -99) < GNEZDO_NE_CHASHCHE:
            zapas = [k for k in svobodnye if ri - kogda.get(k, -99) >= GNEZDO_NE_CHASHCHE]
            if zapas:
                j = min(zapas, key=lambda k: (kogda.get(k, -99), k))
        kogda[j] = ri
        prev_verh = j in VERHNIE
        out.append(j)
    return out


def tona(pr, edl, crops):
    """Насколько светло под каждым гнездом — чтобы выбрать тон субтитра.

    `ЭКРАН.md` §1.1 велит писать светлым по кадру и запрещает подложку. На сырье
    «ПРИМЕР» это работало; серия «Серия» снята в белой
    футболке у белой кирпичной стены — светлый текст ложится на светлое и
    исчезает. `ЭКРАН.md` §0 разрешает нижний скрим, но скрим гасит картинку на всём
    ролик ради нескольких кусков.

    Поэтому не назначаем тон, а меряем: кадр куска кадрируется тем же окном,
    что в сборке, и под каждым гнездом считается средняя яркость. Дальше
    компонент берёт тёмный текст там, где под ним светло, и светлый там, где
    темно. Тон выбирается по числу, а не по впечатлению.
    """
    import subprocess, tempfile
    import numpy as np
    try:
        import cv2
    except ImportError:
        return []
    istochniki = dict(pr.dubli())
    plan = {p["i"]: p for p in crops["план"]}
    out = []
    with tempfile.TemporaryDirectory() as td:
        for i, k in enumerate(edl["куски"]):
            cp = plan.get(i)
            if not cp:
                continue
            cw, ch, x, y = kadr.okno(cp["f1"], cp["eye_x"], cp["eye_y"], cp["py"])
            src = istochniki[k["idx"]]
            vals = []
            for j, ts in enumerate((k["s"] + 0.3, (k["s"] + k["e"]) / 2.0)):
                f = os.path.join(td, "t%d_%d.png" % (i, j))
                cmd = ["ffmpeg", "-v", "error", "-y", "-ss", "%.3f" % ts, "-i", src,
                       "-frames:v", "1",
                       "-vf", "crop=%d:%d:%d:%d,scale=1080:1920" % (cw, ch, x, y), f]
                if subprocess.run(cmd, capture_output=True).returncode != 0:
                    continue
                img = cv2.imread(f)
                if img is None:
                    continue
                g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY).astype("float32") / 255.0
                row = []
                for x0, x1, gy, kegl in GNEZDA:
                    y1 = gy + (kegl * 1.25 * 2) / 1920.0
                    box = g[int(gy * 1920):int(min(y1, 1.0) * 1920),
                            int(x0 * 1080):int(x1 * 1080)]
                    row.append(float(box.mean()) if box.size else 0.5)
                vals.append(row)
            if not vals:
                continue
            L = list(np.mean(np.array(vals), axis=0).round(3))
            out.append({"t": k["t"], "конец": round(k["t"] + k["длит"], 3),
                        "L": [float(v) for v in L]})
    return out


def korobka_lica(pr, edl):
    """Лицо на каждом куске в долях ГОТОВОГО кадра (`ЭКРАН.md` §1)."""
    crops = pr.load("crops.json", required=False)
    zam = pr.load("lico.json", required=False)
    if not crops or not zam:
        return []
    kadr.geometriya_iz(crops)
    out = []
    for p, k in zip(crops["план"], edl["куски"]):
        z = zam[p["i"]]
        if not z:
            continue
        cw, ch, x, y = kadr.okno(p["f1"], p["eye_x"], p["eye_y"], p["py"])
        h = z["h"]
        # Голова: от волос до подбородка. Коробка каскада — бровь…подбородок,
        # глаза стоят на 42 % её высоты, значит подбородок ниже глаз на ~0,6h.
        # Первая версия брала 1,15h вниз и 0,8h вбок — это уже шея и плечи, и
        # коробка накрывала все восемь гнёзд сразу (поймала проверка В10).
        x0 = (z["eye_x"] - 0.62 * h - x) / float(cw)
        x1 = (z["eye_x"] + 0.62 * h - x) / float(cw)
        y0 = (z["eye_y"] - 0.75 * h - y) / float(ch)
        y1 = (z["eye_y"] + 0.75 * h - y) / float(ch)
        out.append({"t": k["t"], "конец": round(k["t"] + k["длит"], 3),
                    "x0": round(max(0.0, x0), 4), "x1": round(min(1.0, x1), 4),
                    "y0": round(max(0.0, y0), 4), "y1": round(min(1.0, y1), 4)})
    return out


# --- ЗАГОЛОВОК ИЗ ГЛАВНОЙ МЫСЛИ ------------------------
# «Сделай, чтоб механизм вычленял главную мысль готового шортса и делал броский
# заголовок, на который хочется кликнуть».
#
# Счёт — по цифрам канала из `ОТБОР.md`, тем же, что и отбор кусков: держат
# конкретика + ставка + интрига результата (VTR 70–89 %), пролистывают
# декларации и абстрактные дихотомии (23–43 %). Формы «Учёные спорят…» и
# «…делает нас глупее?» проверены на канале и проиграли.
#
# ⚠️ Что механизм НЕ делает: он не сочиняет фразу с нуля. Он находит самую
# сильную мысль ролика и **сжимает её собственные слова** до двух строк. Это
# осознанный размен: сгенерированный заголовок первым делом зазвучит как
# сгенерированный, а это ровно то, что `ОТБОР.md`запрещает. Три верхних
# кандидата уходят в `СЛОЙ.md` — если формулировка деревянная, правится словом.
ZAG_STROKA = 30        # знаков в строке заголовка: длиннее не влезает в угол

# ❗Порядок альтернатив — от длинных к коротким. Регулярка выбирает первую
# подошедшую, и с «и» впереди из «И это при том, что я…» срезалось только «И»,
# а в заголовок уезжало «это при том, что я совсем не».
MUSOR_V_ZAG = (r"^(и это при том,? что|это при том,? что|при том,? что|"
               r"потому что|так что|то есть|в общем|короче|значит|плюс|вот|"
               r"ну|а|и)\s+")


def sila_mysli(tekst):
    """Насколько фраза тянет на заголовок. Те же признаки, что в `otbor.py`."""
    t = tekst.lower()
    b = 0.0
    # Цифра держит внимание не сама по себе, а когда за ней СТАВКА — деньги,
    # работа, риск (`ОТБОР.md`: «конкретика + ставка + интрига результата»).
    # Без ставки «от 4 до 12 человек» это просто число, и +3 ему не положено.
    if re.search(r"\d", t):
        # ❗Граница слова в НАЧАЛЕ каждого корня. Без неё «Сейчас» попадало под
        # «час» и любая фраза со словом «сейчас» получала ставку из воздуха.
        stavka = re.search(r"\b(работ|бизнес|деньг|рубл|процент|зарплат|клиент|"
                           r"уволь|замен|рынок|год|час|раз)", t)
        b += 3.0 if stavka else 1.0
    if re.search(r"рубл|доллар|тысяч|миллион|процент|зарплат|деньг|заработ|стоит", t):
        b += 2.0
    # 🔑 Парадокс копится. `ОТБОР.md`: «Вместо вопроса-абстракции — цифра ИЛИ
    # парадокс». Одно отрицание — оговорка, три подряд («не технарь, не
    # айтишник, не программист») — уже конструкция, и держит она сильнее любой
    # цифры без ставки. Раньше отрицание весило фиксированные 2,0 и проигрывало
    # числу «от 4 до 12 человек», в котором ставки нет вовсе.
    otr = len(re.findall(r"\bне\s+[а-яё]", t))
    if otr:
        b += min(1.2 * otr, 3.6)
    # Представление заголовком не работает: в списке того, что держит зрителя
    # (`ОТБОР.md`, VTR 70–89 %), нет ни одного «меня зовут». Там конкретика,
    # ставка и интрига результата — приветствие не даёт ничего из трёх.
    if re.search(r"\bменя зовут\b|\bя\s+сева\b|^привет", t):
        b -= 2.5
    if re.search(r"но |оказал|проблем|ошибк|никто|зря|вместо|обязан|просто накрыло", t):
        b += 1.5
    if re.search(r"\bя\b|\bмне\b|\bменя\b|\bмоя\b|\bмой\b", t):
        b += 1.0
    if re.search(r"прогресс|мир меняется|важно понимать|нужно думать|учёные спорят", t):
        b -= 3.0                      # декларация: проверена на канале и проиграла
    if len(t.split()) < 4:
        b -= 2.0
    return b


def szhat(tekst, predel):
    """Сжимает фразу до строки заголовка её же словами."""
    t = re.sub(MUSOR_V_ZAG, "", tekst.strip(), flags=re.I)
    t = re.sub(r"\s*[.,;:!?…]+\s*$", "", t)
    t = re.sub(r"\s+", " ", t)
    if len(t) <= predel:
        return t
    # режем по смысловой границе, а не по знакам (`ЭКРАН.md` §1): берём самую
    # длинную из уместившихся частей до запятой или союза
    for razrez in re.finditer(r"[,—]|\bи\b|\bно\b|\bчто\b|\bкоторы", t):
        kus = t[:razrez.start()].strip()
        if kus and len(kus) <= predel:
            poslednii = kus
    else:
        poslednii = None
    if poslednii:
        return poslednii
    slova_ = t.split()
    out = []
    for s in slova_:
        if len(" ".join(out + [s])) > predel:
            break
        out.append(s)
    return " ".join(out) if out else t[:predel]


def predlozheniya(words):
    """Речь → предложения. Главная мысль живёт в предложении, а не в реплике.

    Первая версия считала силу по репликам субтитра — а это куски по 4–5 слов,
    и в заголовок попало «в начале 2026 года я». Цифра в куске есть, мысли нет.
    """
    out, cur = [], []
    for w in words:
        cur.append(w)
        if re.search(r"[.!?…]$", w["w"]):
            out.append(cur)
            cur = []
    if cur:
        out.append(cur)
    return out


def zagolovok_iz_rechi(words):
    """Главная мысль ролика → две строки заголовка. Плюс кандидаты на приёмку."""
    kand = []
    for ws in predlozheniya(words):
        tekst = " ".join(w["w"] for w in ws)
        if len(ws) < 5:
            continue
        kand.append((round(sila_mysli(tekst), 1), ws[0]["s"], tekst))
    kand.sort(key=lambda x: (-x[0], x[1]))
    if not kand:
        return None, []

    # 🔑 Перебираем кандидатов, пока пара строк не выйдет ГОДНОЙ. Счёт находит
    # сильную мысль, но не гарантирует, что она сожмётся в заголовок: у самой
    # сильной фразы разрез может прийтись так, что вторая строка начнётся с
    # запятой («сейчас мы регулярно» / «, составом от 4 до 12»). Такой заголовок
    # хуже, чем заголовок из второй по силе мысли, но целый.
    for _, _, glavnaya in kand:
        para = razrezat_v_dve(glavnaya)
        if para:
            return para, kand[:3]
    return None, kand[:3]


def godnaya(s):
    """Строка заголовка не начинается со служебного и не обрывается на нём."""
    if not s or len(s.split()) < 2:
        return False
    if re.match(r"^[\W\d]", s):
        return False
    if re.match(r"^(и|а|но|что|которы|же|ли|бы|от|до|за|из|по|на|в|с|к|у|о)\b", s):
        return False
    # Висящее «не» в конце строки — такой же обрыв, как висящий предлог:
    # «я совсем не» обещает продолжение, которого в строке нет.
    if re.search(r"\b(и|а|но|не|ни|что|которы|же|ли|бы|от|до|за|из|по|на|в|с|к|у|о|"
                 r"совсем|очень|просто|уже)$", s):
        return False
    return True


def razrezat_v_dve(fraza):
    """Фраза → две строки заголовка. None, если целой пары не выходит."""
    t = re.sub(MUSOR_V_ZAG, "", fraza.strip(), flags=re.I)
    t = re.sub(r"\s*[.!?…]+\s*$", "", t)
    granicy = [m.start() for m in re.finditer(r",|\s\bи\b|\s\bно\b|\s\bа\b|\s\bчто\b|\s\bкоторы", t)]
    seredina = len(t) / 2.0
    for razrez in sorted(granicy, key=lambda p: abs(p - seredina)):
        s1 = szhat(t[:razrez], ZAG_STROKA)
        s2 = szhat(re.sub(r"^[\s,—-]+", "", t[razrez:]), ZAG_STROKA)
        if godnaya(s1) and godnaya(s2):
            return {"строка1": s1.lower(), "строка2": s2.lower()}
    s1 = szhat(t, ZAG_STROKA)
    return {"строка1": s1.lower(), "строка2": ""} if godnaya(s1) else None


def pravki_teksta(words, pary):
    """Правка расшифровки для СУБТИТРА — звук при этом не трогается.

    Субтитры вжигаются в кадр, и ошибка распознавания становится ошибкой на
    экране: whisper пишет «законом Еркса -Дотсона», «отдельно называй признак
    качеством», «нейросети» вместо «нейросетям». Правка идёт по цепочке слов,
    время исходной цепочки делится между новыми словами по их длине — синхрон
    (`ЭКРАН.md` §5) сохраняется, потому что меняется подпись, а не тайминг.

        "правки_текста": [["Еркса -Дотсона", "Йеркса — Додсона"], ...]

    Не найденная цепочка — это ошибка, а не мелочь: правка, которую молча
    проглотили, неотличима от выполненной (урок 30.07).
    """
    def golyy(s):
        return re.sub(r"[^0-9a-zа-яё%]+", "", s.lower().replace("ё", "е"))

    for chto, na in pary:
        cel = golyy(chto)
        n_max = len(chto.split()) + 6
        naideno = False
        for i in range(len(words)):
            acc = ""
            for j in range(i, min(i + n_max, len(words))):
                acc += golyy(words[j]["w"])
                if acc == cel:
                    # Хвостовые куски пунктуации («?».») сами по себе пусты и
                    # в сравнение не входят — но остаться на экране отдельной
                    # репликой они не должны. Забираем их в ту же замену.
                    while (j + 1 < len(words) and not golyy(words[j + 1]["w"])):
                        j += 1
                    s0, e0 = words[i]["s"], words[j]["e"]
                    novye = na.split()
                    dlin = float(sum(len(x) for x in novye)) or 1.0
                    t0, zamena = s0, []
                    for x in novye:
                        dt = (e0 - s0) * len(x) / dlin
                        zamena.append({"w": x, "s": round(t0, 3),
                                       "e": round(min(t0 + dt, e0), 3)})
                        t0 += dt
                    zamena[-1]["e"] = e0
                    words[i:j + 1] = zamena
                    naideno = True
                    break
                if len(acc) > len(cel):
                    break
            if naideno:
                break
        if not naideno:
            raise SystemExit("правки_текста: не нашёл в расшифровке «%s»" % chto)
    return words


def snoski(words, cfg, elementy):
    """Плашка-уточнение к сказанному — знак `*` из `ЭКРАН.md` §1.5.

    🔑 ЧИНИТ ТО, ЧТО МОНТАЖОМ НЕ ЧИНИТСЯ. В ролик сказано «Соломон Эш 50 лет
    назад», а опыт Аша — 1951 год, то есть 75. Переснимать одну фразу дороже,
    чем поставить на экран правду: зритель читает дату, а не считает в уме.
    Приём нужен всякий раз, когда речь называет источник неточно, называет
    приблизительно («в каком-то там году») или не называет вовсе — поэтому это
    не заплатка на один ролик, а плашка уточнения:

        "сноски": [{"на": "Соломон Эш 50 лет назад", "текст": "Соломон Аш, 1951"}]

    `на` — цепочка слов расшифровки, к которой плашка привязана; ищется ПОСЛЕ
    `правки_текста`, то есть по тому тексту, который реально попадёт на экран.
    Не нашлась — падаем громко (урок 30.07: молча проигнорированная правка
    неотличима от выполненной).

    Плашка живёт в зоне «низ» — там же, где плашка канала. Две плашки в одном
    месте разом — не приём, а наложение, поэтому пересечение по времени с уже
    собранным элементом тоже роняет сборку, а не решается молча.
    """
    def golyy(x):
        return re.sub(r"[^0-9a-zа-яё%]+", "", x.lower().replace(u"ё", u"е"))

    out = []
    for sn in cfg:
        chto, tekst = sn.get(u"на"), sn.get(u"текст")
        if not chto or not tekst:
            raise SystemExit(u"сноски: нужны оба поля — «на» и «текст»")
        cel, naideno = golyy(chto), None
        for i in range(len(words)):
            acc = ""
            for j in range(i, len(words)):
                acc += golyy(words[j]["w"])
                if acc == cel:
                    naideno = (words[i]["s"], words[j]["e"])
                    break
                if len(acc) > len(cel):
                    break
            if naideno:
                break
        if not naideno:
            raise SystemExit(u"сноски: не нашёл в расшифровке «%s»" % chto)
        t0, t1 = naideno[0], round(naideno[1] + SNOSKA_HVOST, 3)
        for e in elementy + out:
            if t0 < e["конец"] and e["t"] < t1:
                raise SystemExit(
                    u"сноска «%s» (%.2f–%.2f) наложилась на приём «%s» (%.2f–%.2f)"
                    % (tekst, t0, t1, e[u"приём"], e["t"], e["конец"]))
        out.append({u"приём": u"сноска", "t": round(t0, 3), u"конец": t1,
                    u"текст": tekst})
    return out


