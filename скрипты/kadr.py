# -*- coding: utf-8 -*-
"""Вертикальное окно 9:16 из кадра 4K: замер лица → план крупностей.

    python kadr.py --проект "ПРИМЕР"

ДВА РЕШЕНИЯ, ИЗ КОТОРЫХ РАСТЁТ ВЕСЬ ФАЙЛ:
  · **окно не едет за лицом.** Проводка отменена ещё в горизонтали (`ЭКРАН.md`: «кадр либо стоит, либо приближается; вбок и вверх — не едет»),
    в вертикали она заметнее вдвое. Окно считается один раз на кусок;
  · **внутри длинных кусков — медленный наезд.** Тот же приём, что принят на
    шаге 4 горизонтали.

ЛИНИЯ ГЛАЗ ОДНА НА ВЕСЬ РИЛЗ (`ЭКРАН.md` §4). Человек за съёмку пересаживается: если
каждый кусок кадрировать «как снято», на склейке глаза прыгают. Линию задаёт
ролик — взвешенная длительностью медиана, — и под неё встают все куски.

ЧЕМ ВЕРТИКАЛЬ ОТЛИЧАЕТСЯ ОТ ГОРИЗОНТАЛИ. Там окно — доля кадра 16:9, здесь
9:16, и его ширина берётся из высоты: cw = ch·9/16. Поэтому крупность считается
не долей кадра, а **долей лица в готовом кадре** — единственная величина,
которая в вертикали и горизонтали значит одно и то же.
"""
import os
import sys

import numpy as np

BASE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BASE)
import lico                                              # noqa: E402
import obshee                                            # noqa: E402

W4K, H4K = lico.W4K, lico.H4K      # перенастраивается в main() под сырьё
OUT_W, OUT_H = 1080, 1920
AR = 9.0 / 16.0
FPS = 30

# Доля высоты ЛИЦА (бокс бровь–подбородок) в готовом кадре 1080×1920. Это
# единственная величина, которая в вертикали и горизонтали значит одно и то же:
# «доля кадра» в 9:16 и в 16:9 — разные вещи, а «какую часть экрана занимает
# голова» — одна.
DOLYA = {"общий": 0.28, "средний": 0.345}
PY = 0.30            # линия глаз: 30 % высоты ГОТОВОГО кадра, одна на весь ролик
# 🔑 КАДР ЖИВЁТ ВСЕГДА («кадр должен быть живой, то есть
# постоянно медленно и плавно двигаться, увеличиваться, уменьшаться»). Это же
# требует `ЭКРАН.md` §4 из `ref3`: «каждые 3 секунды в кадре что-то должно происходить».
# Первая версия давала наезд только кускам длиннее 5 с — двенадцать кусков из
# двадцати трёх стояли неподвижно.
#
# Скорость постоянная, направление ЧЕРЕДУЕТСЯ: иначе кадр за ролик уползает в
# одну сторону и к концу упирается в предел крупности.
SKOROST = 0.008      # доля кадра в секунду
NAEZD_MAX = 0.045    # больше — движение перестаёт быть «на пороге заметности»
SMENA_NE_CHASHCHE = 1.6   # Правка: короткий кусок держит крупность соседа

# Порог заметности растяжения — ЗАМЕР, а не «любое растяжение». В 4K-кадре
# высотой 2160 любое окно ниже 1920 растягивается по определению, и проверка
# «растягивается — плохо» кричала бы на каждом втором куске. На В13 порог
# заметности замерен как 1,25× (`ЭКРАН.md`); ниже него не считаем.
RASTYAG_MAX = 1.25
LINIYA_MAX = 40      # расхождение линии глаз на склейке, px готового кадра


def geometriya_iz(crops):
    """Поставить размер исходного кадра из плана крупностей.

    Один вход для `titry.py`, `sborka.py` и `proverki.py`: все трое считают окна
    формулой `okno()`, а она клампит по W4K/H4K. Пока эти числа были прибиты к
    горизонтали, вертикальное сырьё давало тихую ложь — окно 2432 px читалось
    как 1352, и проверка В6 жаловалась на растяжение, которого нет, а коробка
    лица накрывала все восемь гнёзд и роняла В10 на каждом куске.
    """
    global W4K, H4K
    if not crops or "кадр" not in crops:
        raise SystemExit("crops.json без размера кадра — пересобери kadr.py")
    W4K, H4K = crops["кадр"]["w"], crops["кадр"]["h"]
    return W4K, H4K


def even(v):
    return int(round(v / 2.0)) * 2


def zamer(pr, edl):
    """Лицо на каждом куске: три момента, медиана по надёжным находкам."""
    # Ролик может быть снят в несколько файлов (ролик): источник берётся у куска,
    # а не у листа целиком.
    istochniki = dict(pr.dubli())
    out = []
    for i, k in enumerate(edl["куски"]):
        src = istochniki[k["idx"]]
        ts = [k["s"] + 0.4, (k["s"] + k["e"]) / 2.0, max(k["s"] + 0.4, k["e"] - 0.4)]
        z = lico.zamer(src, ts)
        out.append(z)
        print("  кусок %2d (%5.2f с): %s" % (
            i + 1, k["e"] - k["s"],
            "лицо h=%.0f, глаза (%.0f, %.0f), кадров %d"
            % (z["h"], z["eye_x"], z["eye_y"], z["кадров"]) if z else "❌ лица нет"))
    return out


def liniya(zam, edl):
    """Одна линия глаз на ролик: медиана, взвешенная длительностью куска."""
    pary = [(z, k["e"] - k["s"]) for z, k in zip(zam, edl["куски"]) if z]
    if not pary:
        raise SystemExit("лиц не нашлось ни на одном куске — смотреть глазами")
    def wmed(key):
        vals = sorted((z[key], w) for z, w in pary)
        half = sum(w for _, w in vals) / 2.0
        acc = 0.0
        for v, w in vals:
            acc += w
            if acc >= half:
                return v
        return vals[-1][0]
    return wmed("eye_x"), wmed("eye_y"), wmed("h")


def okno(f, eye_x, eye_y, py=PY):
    """Окно 9:16 доли f по высоте, поставленное так, чтобы глаза легли на линию."""
    ch = even(H4K * f)
    cw = even(ch * AR)
    x = min(max(eye_x - cw / 2.0, 0), W4K - cw)
    y = min(max(eye_y - py * ch, 0), H4K - ch)
    return cw, ch, int(round(x)), int(round(y))


def main():
    global W4K, H4K
    pr, _ = obshee.argi()
    edl = pr.load("edl.json")
    kuski = edl["куски"]

    # Геометрия — из сырья, а не из константы: серия снята вертикально,
    # «ПРИМЕР» был горизонтальным (см. шапку `lico.py`).
    W4K, H4K = lico.nastroit(dict(pr.dubli())[edl["куски"][0]["idx"]])
    print("сырьё после поворота: %dx%d" % (W4K, H4K))

    print("замер лица по кускам:")
    zam = pr.load("lico.json", required=False)
    if zam is None:
        zam = zamer(pr, edl)
        pr.save("lico.json", zam)
    eye_x, eye_y, face_h = liniya(zam, edl)
    print("\nлиния ролика: глаза (%.0f, %.0f), лицо h=%.0f в кадре 4K"
          % (eye_x, eye_y, face_h))

    # доля высоты кадра под каждую крупность — из доли лица, а не из привычки
    f = {}
    for name, d in DOLYA.items():
        f[name] = min(face_h / d, H4K) / float(H4K)
    print("крупности: общий f=%.3f (окно %dpx, ×%.2f), средний f=%.3f (%dpx, ×%.2f)"
          % (f["общий"], H4K * f["общий"], 1920.0 / (H4K * f["общий"]),
             f["средний"], H4K * f["средний"], 1920.0 / (H4K * f["средний"])))

    # 🔑 КРУПНОСТЬ КУСКА МОЖНО НАЗНАЧИТЬ РУКОЙ.
    #
    # Механизм считает крупность от лица: он ставит глаза на линию и чередует
    # планы. Но иногда содержание куска лежит НЕ в лице. Открывашка ролик — стук
    # мелодии кулаком по столу: смысл в руке, а рука на среднем плане за кадром.
    # Замер этого не видит и видеть не может — он меряет лицо.
    #
    # Поэтому в `proekt.json` можно назвать номер куска (с единицы) и долю
    # высоты кадра: 1.0 — весь кадр целиком, 0.6 — окно в 60 % высоты.
    #
    #     "крупность_куска": {"1": 1.0}
    #
    # Назначенный кусок выпадает из чередования и из наезда: раз крупность
    # выбрана по содержанию, движение к ней ничего не добавляет.
    ruchnye = {}
    for nomer, dolya in (pr.cfg.get("\u043a\u0440\u0443\u043f\u043d\u043e\u0441\u0442\u044c_\u043a\u0443\u0441\u043a\u0430") or {}).items():
        n = int(nomer) - 1
        if not (0 <= n < len(kuski)):
            raise SystemExit("крупность_куска: куска %s в листе нет" % nomer)
        ruchnye[n] = float(dolya)

    # чередование на склейках; кусок короче 1,6 с держит крупность соседа
    plan, tek = [], "общий"
    for i, k in enumerate(kuski):
        dur = k["e"] - k["s"]
        if i and dur >= SMENA_NE_CHASHCHE and (kuski[i - 1]["e"] - kuski[i - 1]["s"]) >= SMENA_NE_CHASHCHE:
            tek = "средний" if tek == "общий" else "общий"
        # движение есть на каждом куске, направление чередуется
        hod = min(NAEZD_MAX, SKOROST * dur)
        naezd = (i % 2 == 0)                       # чётный — приближаемся
        f0 = f[tek] * (1 + hod / 2 if naezd else 1 - hod / 2)
        f1 = f[tek] * (1 - hod / 2 if naezd else 1 + hod / 2)
        # Движение не имеет права утащить кадр глубже порога заметности:
        # наезд подрезает окно, и средний план уходил за 1,25× (поймала В6).
        f_min = (OUT_H / RASTYAG_MAX) / float(H4K)
        f0, f1 = min(max(f0, f_min), 1.0), min(max(f1, f_min), 1.0)
        z = zam[i]
        # кусок без находки лица встаёт на линию ролика — это лучше, чем случайное окно
        ex = z["eye_x"] if z else eye_x
        ey = z["eye_y"] if z else eye_y
        # 🔑 ЛИНИЯ ГЛАЗ — ОДНА ТОЧКА ГОТОВОГО КАДРА, А НЕ ФОРМУЛА.
        # Окно ставится так, чтобы глаза ЭТОГО куска легли на PY высоты вывода.
        # Тогда на склейке глаза не прыгают, чей бы кусок ни стоял рядом:
        # каждый подстраивается сам, а не подгоняется под соседа. Упереться
        # можно только в край кадра — там `py` честно уезжает, и это видно
        # в проверке ниже, а не прячется в округлении.
        # Если на назначенной крупности окно упирается в край кадра и линия
        # глаз уезжает — пробуем вторую крупность. Гейт поймал это на куске
        # «Ну вот я и открыл.»: человек там сидит выше обычного, и общий план
        # физически не мог поставить его глаза на линию, а средний — мог.
        # Смена плана лучше уехавшей линии: первое читается как приём, второе
        # как ошибка.
        def postavit(fx):
            c = H4K * fx
            yy = min(max(ey - PY * c, 0.0), H4K - c)
            return c, (ey - yy) / c

        ch, py = postavit(f0)
        if abs(py - PY) * OUT_H > LINIYA_MAX:
            drugoy = f["средний"] if tek == "общий" else f["общий"]
            ch2, py2 = postavit(drugoy)
            if abs(py2 - PY) < abs(py - PY):
                tek = "средний" if tek == "общий" else "общий"
                f0 = drugoy
                f1 = f0 * NAEZD if dur >= NAEZD_OT else f0
                ch, py = ch2, py2
        # Два соседних куска одной крупности — стык без смены плана. Если
        # предыдущий кончил наездом, начинать с исходного размера нельзя:
        # выйдет отскок на 3,5 %, который глаз ловит как дефект, а не как приём
        # (проверка В3 меряет это отношением). Продолжаем с того размера, на
        # котором сосед остановился.
        if plan and plan[-1]["крупность"] == tek:
            f0 = plan[-1]["f1"]
            f1 = min(max(f0 * (1 - hod if naezd else 1 + hod), f_min), 1.0)
            ch, py = postavit(f0)

        if i in ruchnye:
            f0 = f1 = min(max(ruchnye[i], f_min), 1.0)
            ch, py = postavit(f0)
            plan.append({"i": i, "крупность": "рукой", "f0": round(f0, 5), "f1": round(f1, 5),
                         "eye_x": round(ex, 1), "eye_y": round(ey, 1), "py": round(py, 4),
                         "наезд": False})
            continue

        plan.append({"i": i, "крупность": tek, "f0": round(f0, 5), "f1": round(f1, 5),
                     "eye_x": round(ex, 1), "eye_y": round(ey, 1), "py": round(py, 4),
                     "наезд": abs(f1 - f0) > 1e-6})
    # Геометрия сырья едет вместе с планом: `sborka.py` считает окна теми же
    # формулами, и без неё она клампила бы вертикальный кадр по горизонтальным
    # 3840x2160 — окно уезжало бы за границу кадра молча.
    pr.save("crops.json", {"кадр": {"w": W4K, "h": H4K},
                           "линия": {"eye_x": eye_x, "eye_y": eye_y, "face_h": face_h},
                           "крупности": f, "план": plan})

    # --- проверки, а не «на глаз» ---
    beda = []
    for i, p in enumerate(plan):
        cw, ch, x, y = okno(p["f0"], p["eye_x"], p["eye_y"], p["py"])
        # В1: макушка не режется — над линией глаз нужно место на лоб и волосы
        if p["py"] < 0.17:
            beda.append("кусок %d: над глазами всего %.0f %% окна — макушка режется"
                        % (i + 1, 100 * p["py"]))
        # В2: линия глаз на склейке. Меряется в пикселях ГОТОВОГО кадра —
        # именно их видит глаз, а не доли исходника
        if i and "рукой" not in (p["крупность"], plan[i - 1]["крупность"]):
            d = abs(p["py"] - plan[i - 1]["py"]) * OUT_H
            if d > LINIYA_MAX:
                beda.append("кусок %d: линия глаз уехала на %.0f px против соседнего"
                            % (i + 1, d))
        # В3: скачок крупности меряется ОТНОШЕНИЕМ
        if i:
            r = max(p["f0"], plan[i - 1]["f1"]) / min(p["f0"], plan[i - 1]["f1"])
            if 1.0 < r < 1.06:
                beda.append("кусок %d: скачок крупности %.1f %% — заметно, но не читается"
                            " как смена плана" % (i + 1, 100 * (r - 1)))
        # В4: растяжение кадра сверх замеренного порога заметности
        if OUT_H / float(ch) > RASTYAG_MAX:
            beda.append("кусок %d: окно %d px тянется до %d (×%.2f, порог %.2f)"
                        % (i + 1, ch, OUT_H, OUT_H / float(ch), RASTYAG_MAX))
    print("\nпроверки: %s" % ("чисто" if not beda else "%d замечаний" % len(beda)))
    for b in beda:
        print("  ⚠ " + b)

    # лист контрольных кадров
    lines = ["# КРУПНОСТИ — «%s»\n" % pr.name,
             "Линия ролика: глаза (%.0f, %.0f) в кадре 4K, лицо %.0f px." % (eye_x, eye_y, face_h),
             "Окно 9:16 строится от высоты: `cw = ch·9/16`. Крупность — доля лица",
             "в готовом кадре: общий %.0f %%, средний %.0f %%.\n"
             % (100 * DOLYA["общий"], 100 * DOLYA["средний"]),
             "| # | Крупность | Окно (px) | Наезд | Лицо в кадре |", "|---|---|---|---|---|"]
    for i, p in enumerate(plan, 1):
        cw, ch, x, y = okno(p["f0"], p["eye_x"], p["eye_y"], p["py"])
        z = zam[i - 1]
        dolya = (z["h"] / float(ch)) if z else float("nan")
        lines.append("| %d | %s | %d×%d | %s | %.0f %% |"
                     % (i, p["крупность"], cw, ch, "да" if p["наезд"] else "—", 100 * dolya))
    if beda:
        lines += ["", "## Замечания механизма", ""] + ["- " + b for b in beda]
    pr.text("КРУПНОСТИ.md", "\n".join(lines) + "\n")
    print("план: %s" % pr.path("КРУПНОСТИ.md"))


if __name__ == "__main__":
    main()
