/**
 * Sceny.tsx — набор сцен инфографики для вертикали.
 *
 * 🔑 ИНФОГРАФИКА ПИШЕТСЯ ПОД КАЖДЫЙ РОЛИК, универсального набора не бывает.
 *
 * Инфографика — это сцена, показывающая САМ ОПЫТ, о котором идёт речь: два
 * шрифта с таймерами 8 и 15 минут, ползунок резкости с облаком «кошка?», дуга
 * запоминания, штамп «ПРОВАЛ» на календаре. Субтитры, заголовок, врезка,
 * плашка канала и сноска инфографикой НЕ считаются. Разница не формальная:
 * именно из-за неё слой выглядит наполненным на ролике, где этапа нет вовсе.
 *
 * 🔴 НАБОР ПУСТ ПО ЗАМЫСЛУ — в него вы кладёте свои сцены. Проверка В16 сверяет
 * имя сцены с ЭТИМ файлом, а не со словарём, который её назначил: опечатка в
 * имени даёт пустой экран ровно так же, как отсутствие сцены (тот же приём,
 * что у значков в `Znachki.tsx`). Пока своих сцен нет, держите В16 выключенной
 * — ключ `гейт.требовать_инфографику` в `настройки.json`.
 *
 * Как добавить сцену: компонент + строка в SCENY. Ключ — то, что стоит в
 * `proekt.json` → «инфографика» → «сцена», и оно же попадает в план слоя.
 */
import React from 'react';

export type ПропсСцены = {
  /** Доля прожитого времени сцены, 0…1 — для входа, выхода и внутреннего движения. */
  ход: number;
  /** Подписи и числа сцены: что именно показываем в этом ролике. */
  данные: Record<string, string | number>;
};

const SCENY: Record<string, React.FC<ПропсСцены>> = {
  // Сюда — по одной сцене на ролик. Примеры из уже написанных раскадровок:
  //   два_шрифта:      React.FC — абзац простым и вычурным шрифтом, таймеры 8 и 15
  //   ползунок_резкости: картинка из пятна в чёткость, облако-догадка не гаснет
  //   дуга_запоминания:  тридцать слов, края горят, середина гаснет, поверх дуга
  //   штамп_провал:      календарь перематывается на год, падает штамп «ПРОВАЛ»
};

export const ЕСТЬ_СЦЕНА = (имя: string) => имя in SCENY;

export const Scena: React.FC<{имя: string} & ПропсСцены> = ({имя, ...props}) => {
  const C = SCENY[имя];
  // Молчать нельзя: отсутствующая сцена обязана быть видна гейту, а не
  // превращаться в пустой кадр, который приёмка примет за замысел.
  if (!C) return null;
  return <C {...props} />;
};
