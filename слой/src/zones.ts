import {useVideoConfig} from 'remotion';

/**
 * ГЕОМЕТРИЯ КАДРА — в ДОЛЯХ, а не в пикселях.
 *
 * 🔑 ПОЧЕМУ ДОЛИ. Приёмка идёт на 1080×1920, мастер собирается в 4K. Те же
 * числа в пикселях дали бы в 4K графику вдвое мельче задуманного, а удваивать
 * их руками нельзя: на третьем компоненте забудешь, и слой поедет молча —
 * файл отрендерится, наложится и будет выглядеть исправным. Поэтому размер
 * задаётся долей кадра, а `useK()` переводит эталон в фактический размер:
 *
 *     const k = useK();
 *     fontSize: 104 * k     // 104 px по эталону 1920 — и в 4K это 208
 *
 * Разбор — `ЭКРАН.md` §1.
 */

/** Коэффициент к эталону шириной 1920. В 4K вернёт 2. */
export const useK = () => useVideoConfig().width / 1920;

/**
 * ПОЛЯ ВЕРТИКАЛЬНОГО КАДРА. Считаны один раз здесь, а не подбираются в каждом
 * компоненте: после двадцати клипов правка «отодвинь от края» стоила бы
 * двадцати правок в двадцати местах — и одного забытого.
 *
 * Числа не из вкуса, а из чужого интерфейса. Reels и Shorts рисуют поверх
 * вашего кадра свои элементы, и всё, что попало под них, зритель не увидит:
 *
 *   бок  — 6,5 % ширины. Меньше — текст липнет к краю на телефоне.
 *   верх — 12 % под шапку площадки: имя автора, «Подписаться», звук.
 *   низ  — 14 % под подпись и кнопки; туда же не заезжает плашка.
 *   праваяКолонка — 20 % ширины под столбец иконок (лайк, комментарий,
 *          «поделиться»). Правее этой границы ничего значимого стоять не может.
 *   корпус — 54…68 % высоты: рабочая полоса субтитров и графики. Выше — ворот
 *          и петличка, ниже начинаются руки; и то и другое спорит с текстом.
 */
export const VERT = {
  бок: 0.065,
  верх: 0.12,
  низ: 0.14,
  праваяКолонка: 0.2,
  корпус: [0.54, 0.68] as const,
};
